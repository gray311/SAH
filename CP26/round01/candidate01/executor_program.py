"""Constructor-based circle packing for n=26 circles"""
import numpy as np


def construct_packing():
    """
    Construct a specific arrangement of 26 circles in a unit square
    that attempts to maximize the sum of their radii.
    
    Dense packing approach with circles placed close together.
    """
    n = 26
    centers = np.zeros((n, 2))

    # Dense packing: place circles in a tight grid pattern
    # The compute_max_radii function will scale them down appropriately
    
    # Create a 5x5 grid but skip some positions to get 26 circles
    # Grid spacing of 0.25 gives us 25 positions, add 1 more
    
    grid_spacing = 0.25
    offset = 0.125  # Start at center of first cell
    
    idx = 0
    for row in range(5):
        for col in range(5):
            if idx >= 26:
                break
            x = offset + col * grid_spacing
            y = offset + row * grid_spacing
            centers[idx] = [x, y]
            idx += 1
    
    # Add one more circle in a gap
    centers[25] = [0.5, 0.5]  # Center
    
    # Clip to ensure inside square
    centers = np.clip(centers, 0.01, 0.99)
    
    # Compute maximum valid radii
    radii = compute_max_radii(centers)
    sum_radii = np.sum(radii)
    
    return centers, radii, sum_radii


def compute_max_radii(centers):
    """
    Compute the maximum possible radii for each circle position
    such that they don't overlap and stay within the unit square.
    """
    n = centers.shape[0]
    radii = np.ones(n)

    # First, limit by distance to square borders
    for i in range(n):
        x, y = centers[i]
        radii[i] = min(x, y, 1 - x, 1 - y)

    # Then, limit by distance to other circles
    for i in range(n):
        for j in range(i + 1, n):
            dist = np.sqrt(np.sum((centers[i] - centers[j]) ** 2))

            if radii[i] + radii[j] > dist:
                scale = dist / (radii[i] + radii[j])
                radii[i] *= scale
                radii[j] *= scale

    return radii
