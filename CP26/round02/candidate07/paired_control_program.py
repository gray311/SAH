"""Constructor-based circle packing for n=26 circles - Sparse hexagonal"""
import numpy as np


def construct_packing():
    """
    Construct a specific arrangement of 26 circles in a unit square
    using a sparse hexagonal pattern for maximum sum of radii.

    Returns:
        Tuple of (centers, radii, sum_of_radii)
    """
    n = 26
    centers = np.zeros((n, 2))
    
    # Sparse hexagonal pattern - circles placed further apart
    # This allows for larger radii after constraint propagation
    
    # Row 1 (5 circles): y = 0.1, wider spacing
    y1 = 0.1
    for i in range(5):
        x = 0.1 + i * 0.25  # wider spacing
        centers[i] = [x, y1]
    
    # Row 2 (4 circles): y = y1 + sqrt(3)/2 * 0.25, offset
    y2 = y1 + np.sqrt(3)/2 * 0.25
    for i in range(4):
        x = 0.125 + i * 0.25
        centers[5 + i] = [x, y2]
    
    # Row 3 (5 circles): y = y1 + sqrt(3) * 0.25
    y3 = y1 + np.sqrt(3) * 0.25
    for i in range(5):
        x = 0.1 + i * 0.25
        centers[9 + i] = [x, y3]
    
    # Row 4 (4 circles): y = y1 + 1.5*sqrt(3)*0.25, offset
    y4 = y1 + 1.5 * np.sqrt(3) * 0.25
    for i in range(4):
        x = 0.125 + i * 0.25
        centers[14 + i] = [x, y4]
    
    # Row 5 (5 circles): y = y1 + 2*sqrt(3)*0.25
    y5 = y1 + 2 * np.sqrt(3) * 0.25
    for i in range(5):
        x = 0.1 + i * 0.25
        centers[18 + i] = [x, y5]
    
    # Clip to unit square
    centers = np.clip(centers[:n], 0.01, 0.99)
    
    # Compute maximum valid radii
    radii = compute_max_radii(centers)
    
    sum_radii = np.sum(radii)
    
    return centers, radii, sum_radii


def compute_max_radii(centers):
    """
    Compute the maximum possible radii for each circle position
    such that they don't overlap and stay within the unit square.

    Args:
        centers: np.array of shape (n, 2) with (x, y) coordinates

    Returns:
        np.array of shape (n) with radius of each circle
    """
    n = centers.shape[0]
    radii = np.ones(n)

    # First, limit by distance to square borders
    for i in range(n):
        x, y = centers[i]
        radii[i] = min(x, y, 1 - x, 1 - y)

    # Then, limit by distance to other circles
    for i in range(n):
        for j in range(i + 1, n):
            dist = np.sqrt(np.sum((centers[i] - centers[j]) ** 2))
            if radii[i] + radii[j] > dist:
                scale = dist / (radii[i] + radii[j])
                radii[i] *= scale
                radii[j] *= scale

    return radii


