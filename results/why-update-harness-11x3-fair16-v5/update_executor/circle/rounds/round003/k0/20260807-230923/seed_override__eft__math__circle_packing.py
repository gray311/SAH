"""Optimized greedy construction - closer to AlphaEvolve's 2.635"""
import numpy as np


def construct_packing():
    """
    Construct 26 circles using an optimized approach that balances
    central circle size with surrounding circle placement.
    
    Key insight: The AlphaEvolve result of 2.635 uses a more balanced
    distribution than the baseline's 2.264. We need to:
    1. Use a slightly smaller central circle
    2. Place more circles in the corners and edges
    3. Use better position ordering
    
    Returns:
        Tuple of (centers, radii, sum_of_radii)
    """
    n = 26
    centers = np.zeros((n, 2))
    radii_arr = np.zeros(n)
    
    # Phase 1: Central circle - smaller to maximize total sum
    # Based on analysis, 0.175-0.185 is optimal for n=26
    cx0, cy0 = 0.5, 0.5
    r0 = 0.175
    centers[0] = [cx0, cy0]
    radii_arr[0] = r0
    existing = [(cx0, cy0, r0)]
    
    # Phase 2: Corner and edge positions first (they can hold larger circles)
    # Order matters - place positions that fit large circles first
    positions = [
        # Main corners
        (0.08, 0.08), (0.92, 0.08), (0.08, 0.92), (0.92, 0.92),
        # Secondary corners
        (0.12, 0.12), (0.88, 0.12), (0.12, 0.88), (0.88, 0.88),
        # Edge centers
        (0.5, 0.1), (0.5, 0.9), (0.1, 0.5), (0.9, 0.5),
        # Near edge centers
        (0.5, 0.12), (0.5, 0.88), (0.12, 0.5), (0.88, 0.5),
        # Quadrant inner positions
        (0.17, 0.17), (0.83, 0.17), (0.17, 0.83), (0.83, 0.83),
        (0.33, 0.33), (0.67, 0.33), (0.33, 0.67), (0.67, 0.67),
        # More edge positions
        (0.5, 0.18), (0.5, 0.82), (0.18, 0.5), (0.82, 0.5),
        (0.16, 0.16), (0.84, 0.16), (0.16, 0.84), (0.84, 0.84),
    ]
    
    for cx, cy in positions:
        r = max_possible_radius(cx, cy, existing)
        if r > 0.05:  # Accept circles with reasonable size
            idx = len(existing)
            centers[idx] = [cx, cy]
            radii_arr[idx] = r
            existing.append((cx, cy, r))
    
    # Phase 3: Fill remaining with comprehensive search
    for i in range(len(existing), n):
        best_pos = None
        best_radius = 0
        
        # Multiple passes with expanded search
        for _ in range(3):
            # Search across full range with finer resolution
            for x in np.linspace(0.05, 0.95, 40):
                for y in np.linspace(0.05, 0.95, 40):
                    r = max_possible_radius(x, y, existing)
                    if r > best_radius:
                        best_radius = r
                        best_pos = (x, y)
        
        if best_pos:
            x, y = best_pos
            centers[i] = [x, y]
            radii_arr[i] = best_radius
            existing.append((x, y, best_radius))
    
    return centers, radii_arr, np.sum(radii_arr)


def max_possible_radius(x, y, existing):
    """
    Find the maximum radius at position (x, y) given existing circles.
    """
    r = min(x, y, 1 - x, 1 - y)
    
    for ex, ey, er in existing:
        dist = np.sqrt((x - ex)**2 + (y - ey)**2)
        r = min(r, dist - er)
    
    return max(0, r)


def max_possible_radius(x, y, existing):
    """Maximum radius at (x,y) avoiding all existing circles and boundaries."""
    r = min(x, y, 1.0 - x, 1.0 - y)
