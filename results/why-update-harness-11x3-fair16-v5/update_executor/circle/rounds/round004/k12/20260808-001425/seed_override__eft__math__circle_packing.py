"""
Improved hexagonal packing with larger radius for n=26.

Tries to maximize radius while maintaining non-overlap.
Uses a slightly larger base radius with careful positioning.
"""
import numpy as np


def construct_packing():
    """
    Construct 26 circles using improved hexagonal pattern.
    
    Tries larger radius values to maximize sum of radii.
    
    Returns:
        Tuple of (centers, radii, sum_of_radii)
    """
    n = 26
    
    # Try progressively larger radii to find optimal
    best_sum = 0
    best_config = None
    
    for base_r in np.linspace(0.075, 0.11, 15):
        centers, radii_arr, valid, actual_sum = _try_radius(n, base_r)
        if valid and actual_sum > best_sum:
            best_sum = actual_sum
            best_config = (centers, radii_arr)
    
    if best_config:
        centers, radii_arr = best_config
    
    centers = np.array(centers)
    radii_arr = np.array(radii_arr)
    
    sum_radii = np.sum(radii_arr)
    
    return centers, radii_arr, sum_radii


def _try_radius(n, base_r):
    """Try to place n circles with given base radius."""
    centers = []
    radii_arr = []
    
    # Hexagonal grid parameters
    v_spacing = np.sqrt(3) * base_r
    h_spacing = 2 * base_r
    
    row = 0
    y = base_r
    count = 0
    
    while count < n and y <= 1 - base_r:
        offset = (row % 2) * base_r
        x = base_r + offset
        while x <= 1 - base_r and count < n:
            cx, cy = x, y
            centers.append((cx, cy))
            radii_arr.append(base_r)
            count += 1
            x += h_spacing
        
        y += v_spacing
        row += 1
    
    # Fill remaining with gap circles (smaller radius)
    while len(centers) < n:
        gap_positions = [
            (0.3, 0.3), (0.7, 0.3), (0.3, 0.7), (0.7, 0.7),
            (0.5, 0.2), (0.5, 0.8), (0.2, 0.5), (0.8, 0.5),
            (0.15, 0.15), (0.85, 0.15), (0.15, 0.85), (0.85, 0.85),
        ]
        for gx, gy in gap_positions:
            if len(centers) >= n:
                break
            small_r = base_r * 0.7
            centers.append((gx, gy))
            radii_arr.append(small_r)
    
    # Trim to exactly n
    if len(centers) > n:
        centers = centers[:n]
        radii_arr = radii_arr[:n]
    
    # Verify validity
    valid = _verify_no_overlap(np.array(centers), np.array(radii_arr))
    actual_sum = np.sum(radii_arr)
    
    return centers, radii_arr, valid, actual_sum


def _verify_no_overlap(centers, radii):
    """Verify no circles overlap."""
    for i in range(len(centers)):
        for j in range(i + 1, len(centers)):
            dx = centers[i, 0] - centers[j, 0]
            dy = centers[i, 1] - centers[j, 1]
            dist = np.sqrt(dx**2 + dy**2)
            min_dist = radii[i] + radii[j]
            if dist < min_dist - 1e-6:
                return False
    return True
